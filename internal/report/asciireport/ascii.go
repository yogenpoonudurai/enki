// Package asciireport renders a standalone ASCII posture report.
package asciireport

import (
	"fmt"
	"io"
	"regexp"
	"strings"

	"github.com/yogenpoonudurai/enki/internal/finding"
	"github.com/yogenpoonudurai/enki/internal/report"
)

const (
	innerWidth = 76
	totalWidth = innerWidth + 2
)

var ansiRE = regexp.MustCompile("\x1b\\[[0-9;]*m")

func vlen(s string) int {
	return len([]rune(ansiRE.ReplaceAllString(s, "")))
}

func pad(s string, n int) string {
	if l := vlen(s); l >= n {
		return s
	}
	return s + strings.Repeat(" ", n-vlen(s))
}

func trunc(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	if n <= 1 {
		return string(r[:n])
	}
	return string(r[:n-1]) + "…"
}

// Write renders the report without ANSI codes (safe for files).
func Write(w io.Writer, rep *report.Report) error {
	_, err := io.WriteString(w, Render(rep, false))
	return err
}

// Render builds the ASCII report.
func Render(rep *report.Report, color bool) string {
	var b strings.Builder

	top := "╔" + strings.Repeat("═", innerWidth) + "╗"
	bottom := "╚" + strings.Repeat("═", innerWidth) + "╝"
	box := func(s string) {
		fmt.Fprintf(&b, "║ %s ║\n", pad(trunc(s, innerWidth-2), innerWidth-2))
	}

	b.WriteString(top + "\n")
	left := "ENKI · AI SECURITY POSTURE REPORT"
	when := rep.Scan.StartedAt.Local().Format("2006-01-02 15:04")
	gap := innerWidth - 2 - vlen(left) - len(when)
	if gap < 1 {
		gap = 1
	}
	box(left + strings.Repeat(" ", gap) + when)
	scope := rep.Scan.Scope
	if scope == "" {
		scope = "full"
	}
	box(fmt.Sprintf("%s · %s/%s · %s · scope %s · %s", rep.Scan.Host, rep.Scan.OS, rep.Scan.Arch, rep.Scan.User, scope, rep.Scan.ID))
	b.WriteString(bottom + "\n\n")

	score := rep.Summary.Score
	filled := score * 30 / 100
	bar := strings.Repeat("█", filled) + strings.Repeat("░", 30-filled)
	scoreColor := "\x1b[38;2;63;185;80m"
	if score < 50 {
		scoreColor = "\x1b[38;2;255;71;87m"
	} else if score < 80 {
		scoreColor = "\x1b[38;2;255;217;61m"
	}
	barOut := bar
	if color {
		barOut = scoreColor + bar + "\x1b[0m"
	}
	fmt.Fprintf(&b, "  POSTURE SCORE   %3d / 100   %s\n", score, barOut)
	fmt.Fprintf(&b, "  VERDICT         %s — %d critical, %d high\n\n",
		badge(color, verdictSeverity(rep.Summary.Verdict), rep.Summary.Verdict),
		rep.Summary.Counts["CRITICAL"], rep.Summary.Counts["HIGH"])

	b.WriteString("  SEVERITY     COUNT   DISTRIBUTION\n")
	order := []finding.Severity{
		finding.SeverityCritical, finding.SeverityHigh, finding.SeverityMedium,
		finding.SeverityLow, finding.SeverityInfo,
	}
	max := 1
	for _, s := range order {
		if c := rep.Summary.Counts[string(s)]; c > max {
			max = c
		}
	}
	for _, s := range order {
		count := rep.Summary.Counts[string(s)]
		barLen := count * 30 / max
		if count > 0 && barLen == 0 {
			barLen = 1
		}
		fmt.Fprintf(&b, "  %s   %5d   %s\n", badge(color, s, fmt.Sprintf("%-9s", s)), count,
			badge(color, s, strings.Repeat("█", barLen)))
	}
	b.WriteString("\n  " + strings.Repeat("─", totalWidth-4) + "\n\n")

	b.WriteString("  FINDINGS\n\n")
	shown := 0
	for _, f := range report.CollapseSBOM(rep.Findings) {
		if shown >= 24 {
			break
		}
		fmt.Fprintf(&b, "  %s %-8s %s\n", badge(color, f.Severity, fmt.Sprintf("%-8s", f.Severity)), f.RuleID, f.Title)
		if loc := f.Location.String(); loc != "" {
			fmt.Fprintf(&b, "           %s\n", loc)
		}
		if f.Evidence != "" {
			for _, line := range wrap(f.Evidence, 66) {
				fmt.Fprintf(&b, "           evidence: %s\n", line)
			}
		}
		if f.Remediation != nil {
			fmt.Fprintf(&b, "           respond (%s): %s\n", f.Remediation.Class, f.Remediation.Summary)
			if f.Remediation.Command != "" {
				fmt.Fprintf(&b, "           run: %s\n", f.Remediation.Command)
			}
		}
		b.WriteString("\n")
		shown++
	}
	if rest := len(rep.Findings) - shown; rest > 0 {
		fmt.Fprintf(&b, "  … %d more finding(s) — see the JSON output for the full list\n\n", rest)
	}

	if len(rep.Coverage) > 0 {
		b.WriteString("  COVERAGE GAPS (results may be incomplete)\n")
		for _, g := range rep.Coverage {
			kind := g.Kind
			if kind == "" {
				kind = "unknown"
			}
			fmt.Fprintf(&b, "  · [%s/%s] %s\n", g.Module, kind, g.Reason)
		}
		b.WriteString("\n")
	}

	b.WriteString("  MODULES\n")
	for i, m := range rep.Modules {
		status := fmt.Sprintf("%d finding(s) · %dms", m.Findings, m.DurationMS)
		if m.Skipped {
			status = "skipped (not applicable in this scope)"
		}
		if m.Error != "" {
			status = "error: " + m.Error
		}
		fmt.Fprintf(&b, "  · %-20s %s", m.Name, status)
		if i%2 == 1 {
			b.WriteString("\n")
		} else {
			b.WriteString("   ")
		}
	}
	if len(rep.Modules)%2 == 1 {
		b.WriteString("\n")
	}

	fmt.Fprintf(&b, "\n  generated by enki %s · rule pack %s · schema %s\n",
		rep.Tool.Version, rep.Tool.RulePack, rep.Tool.SchemaVersion)
	return b.String()
}

func verdictSeverity(verdict string) finding.Severity {
	switch verdict {
	case "AT RISK":
		return finding.SeverityCritical
	case "ATTENTION":
		return finding.SeverityHigh
	case "REVIEW":
		return finding.SeverityMedium
	default:
		return finding.SeverityLow
	}
}

func badge(color bool, sev finding.Severity, text string) string {
	if !color {
		return text
	}
	return report.Paint(true, sev, text)
}

func wrap(s string, width int) []string {
	words := strings.Fields(s)
	if len(words) == 0 {
		return nil
	}
	var lines []string
	var cur string
	for _, w := range words {
		if cur == "" {
			cur = w
			continue
		}
		if len([]rune(cur))+1+len([]rune(w)) <= width {
			cur += " " + w
			continue
		}
		lines = append(lines, cur)
		cur = w
	}
	if cur != "" {
		lines = append(lines, cur)
	}
	return lines
}
